import { useEffect, useRef, type CSSProperties } from 'react'
import type { MenuData } from '@/api/menu'
import { ChatIcon, FacebookIcon, InstagramIcon } from '@/components/icons'
import { JuneLogo } from '@/components/JuneLogo'
import { onFrame } from '@/lib/frame'
import { clamp, ease } from '@/lib/math'
import { Drips } from './Drips'

export function End({ line, social }: { line: MenuData['line']; social: MenuData['social'] }) {
  const markRef = useRef<HTMLDivElement>(null)

  // the big logo rises as it scrolls into view; its palm opens once on the way up, then sways while on screen
  useEffect(() => {
    const mark = markRef.current
    if (!mark) return
    const logo = mark.querySelector('.june-logo')
    let top = 0, height = 0, opened = false
    const io = new IntersectionObserver((entries) => logo?.classList.toggle('paused', !entries[0]?.isIntersecting))
    io.observe(mark)
    const off = onFrame({
      read: ({ scrolled }) => {
        if (!scrolled) return
        const r = mark.getBoundingClientRect()
        top = r.top
        height = r.height
      },
      write: ({ scrolled, vh }) => {
        if (!scrolled) return
        const m = ease(clamp((vh - top + height * 0.45) / (vh * 0.6)))
        mark.style.setProperty('--m', m.toFixed(3))
        if (!opened && m > 0.15) {
          opened = true
          logo?.classList.replace('wait', 'go')
        }
      },
    })
    return () => {
      off()
      io.disconnect()
    }
  }, [])

  return (
    <section className="end" id="end" data-nav="dark">
      <Drips count={26} />
      <h2 className="reveal">อยากชิมแล้วใช่ไหม ทักมาสั่งได้เลย</h2>
      <a className="btn reveal" style={{ '--i': 1 } as CSSProperties} href={line.addUrl} target="_blank" rel="noopener">
        ทักสั่งทาง LINE
      </a>
      <div className="contact reveal" style={{ '--i': 2 } as CSSProperties}>
        <h3>ติดต่อร้าน</h3>
        <div className="social">
          <a href={line.addUrl} target="_blank" rel="noopener">
            <ChatIcon />
            LINE {line.oaId}
          </a>
          {social.instagram && (
            <a href={social.instagram} target="_blank" rel="noopener">
              <InstagramIcon />
              Instagram
            </a>
          )}
          {social.facebook && (
            <a href={social.facebook} target="_blank" rel="noopener">
              <FacebookIcon />
              Facebook
            </a>
          )}
        </div>
      </div>
      <div className="qr reveal" style={{ '--i': 3 } as CSSProperties}>
        {/* QR is generated by our own server (segno), not user content */}
        <span dangerouslySetInnerHTML={{ __html: line.qrSvg }} />
        <p>
          สแกนเพื่อเพิ่มเพื่อนใน LINE<b>{line.oaId}</b>
        </p>
      </div>
      <div ref={markRef} className="mark" aria-hidden="true">
        <JuneLogo className="wait" />
      </div>
      <p className="note">หน้าตัวอย่าง: ราคาและชื่อเมนูบางรายการเป็นข้อมูลจำลอง ต้องแก้เป็นข้อมูลจริงก่อนใช้งาน</p>
    </section>
  )
}
